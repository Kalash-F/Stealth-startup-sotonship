"""Load UN Comtrade's "Combined HS" list (HS.json) as SQL: comtrade_hs2 -> comtrade_hs4 -> comtrade_hs6.

Run:  python backend/scripts/load_hs_json.py [--json HS.json] [--out DIR] [--db hs.db]

Same table layout as fetch_hs_codes.py (code, parent code, name), with a `comtrade_` prefix so both
sets can sit in one database. HS.json is the UN Comtrade reference file for classification "HS"
(all HS revisions combined): a `results` list of {id, text, parent, ...}, where text is
"<id> - <name>". The name is the text after that prefix, otherwise unchanged (spacing, case and
trailing spaces as in the file). The "TOTAL" row is skipped; chapter 77 (reserved) has no headings
and is kept.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
from pathlib import Path

from fetch_hs_codes import ROOT, inserts_sql, load_sqlite, schema_sql

PREFIX = "comtrade_"
OUT = ROOT / "data" / "reference" / "hs" / "comtrade"


def read_rows(path: Path) -> tuple[list[tuple], list[tuple], list[tuple]]:
    """hs2, hs4 and hs6 rows from HS.json, checking codes, parents and the "<id> - " prefix."""
    results = json.loads(path.read_text(encoding="utf-8-sig"))["results"]
    levels: dict[int, dict[str, str]] = {2: {}, 4: {}, 6: {}}
    for r in results:
        code, text, parent = r["id"], r["text"], r["parent"]
        if code == "TOTAL":
            continue
        if len(code) not in levels or not code.isdigit() or code in levels[len(code)]:
            raise ValueError(f"{path}: unexpected or duplicate id {code!r}")
        if parent != (code[:-2] if len(code) > 2 else "TOTAL"):
            raise ValueError(f"{path}: {code} has parent {parent!r}")
        if not text.startswith(f"{code} - ") or not text[len(code) + 3 :].strip():
            raise ValueError(f"{path}: {code} has text {text!r}")
        levels[len(code)][code] = text[len(code) + 3 :]

    orphans = [c for n in (4, 6) for c in levels[n] if c[: n - 2] not in levels[n - 2]]
    if orphans:
        raise ValueError(f"{path}: codes without a parent: {orphans[:10]}")
    hs2 = sorted(levels[2].items())
    hs4 = [(c, c[:2], name) for c, name in sorted(levels[4].items())]
    hs6 = [(c, c[:4], name) for c, name in sorted(levels[6].items())]
    print(f"{len(hs2)} hs2, {len(hs4)} hs4, {len(hs6)} hs6 rows")
    return hs2, hs4, hs6


def main() -> int:
    """Read HS.json, write SQL, check it reproduces the file, and with --db load it."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", type=Path, default=ROOT / "HS.json")
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--db", type=Path, help="also (re)create the tables in this SQLite database")
    a = ap.parse_args()

    hs2, hs4, hs6 = read_rows(a.json)
    head = (
        f"-- Generated by backend/scripts/load_hs_json.py on {dt.date.today().isoformat()}. Do not edit by hand.\n"
        f"-- Source: {a.json.name}, UN Comtrade reference list for classification HS (Combined HS).\n"
        "-- Names are the file's text after the '<code> - ' prefix, otherwise unchanged.\n"
        "-- Encoding: UTF-8. Portable SQL (SQLite and PostgreSQL).\n\n"
    )
    t = {n: f"{PREFIX}hs{n}" for n in (2, 4, 6)}
    a.out.mkdir(parents=True, exist_ok=True)
    files = {
        "00_schema.sql": schema_sql(PREFIX),
        f"01_{t[2]}.sql": inserts_sql(t[2], ["hs2_code", "name"], hs2),
        f"02_{t[4]}.sql": inserts_sql(t[4], ["hs4_code", "hs2_code", "name"], hs4),
        f"03_{t[6]}.sql": inserts_sql(t[6], ["hs6_code", "hs4_code", "name"], hs6),
    }
    for name, body in files.items():
        (a.out / name).write_text(head + body, encoding="utf-8")
        print("wrote", a.out / name)

    paths = [a.out / name for name in files]
    expected = {t[2]: hs2, t[4]: hs4, t[6]: hs6}
    load_sqlite(":memory:", paths, expected)
    if a.db:
        load_sqlite(a.db, paths, expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
