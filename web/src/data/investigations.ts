export const investigations: Investigation[] = drafts.map((d) => {
  const { score, band } = scoreFlags(d.flags);
  const line_items = d.invoice.line_items.map((l) => ({
    ...l,
    unit_price_usd: l.unit_price_usd !== undefined ? l.unit_price_usd : l.hs6 ? l.unit_price : null,
  }));
  return { ...d, invoice: { ...d.invoice, line_items }, priority_score: score, priority_band: band };
});

