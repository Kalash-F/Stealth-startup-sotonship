import type { Flag, Investigation, Party, PriorityBand, AddressType } from "./types";

/** Build a Party from an entity record so names and countries never drift. */
function party(entityId: string, address: string, address_type: AddressType = "commercial"): Party {
  const e = entityById(entityId);
  if (!e) throw new Error(`Unknown entity ${entityId}`);
  return { name: e.name, address, country: e.country, address_type, entityId };
}

/** plan.md §4.3: high 40, medium 15, low 5 per flag, capped at 100. */
export function scoreFlags(flags: Flag[]): { score: number; band: PriorityBand } {
  const score = Math.min(100, flags.reduce((s, f) => s + severityWeight[f.severity], 0));
  const band: PriorityBand = score >= 60 ? "review_now" : score >= 25 ? "review" : "low";
  return { score, band };
}

