// Generates src/components/marketing/map/land-dots.ts: a run-length encoded grid
// of land cells (Natural Earth 1:110m via world-atlas), sampled every STEP degrees.
// Run once with `node scripts/build-land-dots.mjs`; the output is committed.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"));
const land = feature(topo, topo.objects.land);

const STEP = 1.25;
const LON0 = -100, LON1 = 180, LAT0 = 80, LAT1 = -45;
const rows = [];
for (let lat = LAT0; lat >= LAT1; lat -= STEP) {
  const runs = [];
  let start = -1;
  const cols = Math.round((LON1 - LON0) / STEP);
  for (let c = 0; c <= cols; c++) {
    const lon = LON0 + c * STEP;
    const on = c < cols && geoContains(land, [lon, lat]);
    if (on && start < 0) start = c;
    if (!on && start >= 0) { runs.push(`${start.toString(36)}.${(c - start).toString(36)}`); start = -1; }
  }
  rows.push(runs.join(" "));
}
const out = `// Generated by scripts/build-land-dots.mjs from Natural Earth 1:110m land (public domain). Do not edit.
// Each row is a latitude band from LAT0 southward; runs are "startColumn.length" in base 36.
export const LAND = {
  lon0: ${LON0},
  lat0: ${LAT0},
  step: ${STEP},
  rows: ${JSON.stringify(rows)},
} as const;
`;
writeFileSync(new URL("../src/components/marketing/map/land-dots.ts", import.meta.url), out);
console.log(rows.length, "rows", out.length, "bytes");
